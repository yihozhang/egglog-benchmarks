#!/usr/bin/env python3
"""Generate matmul-assoc-<n>.egg: matrix-chain associativity from foresight (CC'26, section 7.2).

Follows foresight's examples/mm (Rules.scala, MatmulBenchmarks.scala): a chain of n
multiplications of 10x10 matrices, Mul(...Mul(Mul(Mat, Mat), Mat)..., Mat), the two
associativity rules, run to saturation. The paper's instances are n = 20, 40, 80.
Extraction with the scalar-multiplication cost function is not part of the benchmark.
"""

import sys
from pathlib import Path

HEADER = """;; Matrix-chain associativity, {n} multiplications. Generated by gen.py from foresight's examples/mm; do not edit.
(datatype Linalg
    (Mat i64 i64)
    (Mul Linalg Linalg))

(rewrite (Mul (Mul x y) z) (Mul x (Mul y z)))                   ; mul-associativity1
(rewrite (Mul x (Mul y z)) (Mul (Mul x y) z))                   ; mul-associativity2

"""


def chain(n: int) -> str:
    e = "(Mat 10 10)"
    for _ in range(n):
        e = f"(Mul {e} (Mat 10 10))"
    return e


def main():
    out = Path(__file__).parent
    for n in map(int, sys.argv[1:] or ["20", "40", "80", "160", "320"]):
        program = HEADER.format(n=n) + f"(let $m {chain(n)})\n"
        (out / f"matmul-assoc-{n}.egg").write_text(program + "\n(run-schedule (saturate (run)))\n")
        # oatlog cannot parse (saturate ...); its port is the same program without the schedule,
        # and the marker tells systems/oatlog/build to generate a saturation loop around step().
        (out / "oatlog").mkdir(exist_ok=True)
        (out / "oatlog" / f"matmul-assoc-{n}.egg").write_text(";; oatlog-port: saturate\n" + program)
        print(f"matmul-assoc-{n}.egg")


if __name__ == "__main__":
    main()
