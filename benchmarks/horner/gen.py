#!/usr/bin/env python3
"""Generate horner-<n>.egg: Horner's method benchmark from foresight (CC'26, section 7.2).

Language, rules and the polynomial follow foresight's examples/poly (Rules.scala,
PolyBenchmarks.scala): Peano exponents (Zero/Succ), 11 rewrites, the polynomial of
degree n in x with symbolic coefficients a, b, c, ... built as
  ((a_n * x^n + a_{n-1} * x^{n-1}) + ...) + a_0
and run to saturation. The paper's instances are n = 5 and 6; larger n are added here.
Extraction (the paper's cost-function step) is not part of the benchmark.
"""

import sys
from pathlib import Path

HEADER = """;; Horner's method, degree {n}. Generated by gen.py from foresight's examples/poly; do not edit.
(datatype Arith
    (Zero)
    (Succ Arith)
    (Var String)
    (Add Arith Arith)
    (Mul Arith Arith)
    (Pow Arith Arith))

(rewrite (Add x y) (Add y x))                                   ; add-commutativity
(rewrite (Mul x y) (Mul y x))                                   ; mul-commutativity
(rewrite (Add (Add x y) z) (Add x (Add y z)))                   ; add-associativity1
(rewrite (Add x (Add y z)) (Add (Add x y) z))                   ; add-associativity2
(rewrite (Mul (Mul x y) z) (Mul x (Mul y z)))                   ; mul-associativity1
(rewrite (Mul x (Mul y z)) (Mul (Mul x y) z))                   ; mul-associativity2
(rewrite (Mul x (Add a b)) (Add (Mul x a) (Mul x b)))           ; distributivity1
(rewrite (Add (Mul x a) (Mul x b)) (Mul x (Add a b)))           ; distributivity2
(rewrite (Mul x (Succ (Zero))) x)                               ; multiplicative-identity
(rewrite (Pow x (Zero)) (Succ (Zero)))                          ; power-null
(rewrite (Pow x (Succ n)) (Mul x (Pow x n)))                    ; power-reduction

"""


def const(i: int) -> str:
    return "(Zero)" if i == 0 else f"(Succ {const(i - 1)})"


def polynomial(n: int) -> str:
    x = '(Var "x")'
    coeffs = [f'(Var "{chr(ord("a") + i)}")' for i in range(n + 1)]  # a_0 .. a_n
    terms = [c if i == 0 else f"(Mul {c} (Pow {x} {const(i)}))" for i, c in enumerate(coeffs)]
    terms.reverse()  # a_n x^n first, like foresight's zipWithIndex.reverse
    acc = terms[0]
    for t in terms[1:]:
        acc = f"(Add {acc} {t})"
    return acc


def main():
    out = Path(__file__).parent
    for n in map(int, sys.argv[1:] or ["5", "6", "7", "8", "9"]):
        program = HEADER.format(n=n) + f"(let $p {polynomial(n)})\n"
        (out / f"horner-{n}.egg").write_text(program + "\n(run-schedule (saturate (run)))\n")
        # oatlog cannot parse (saturate ...); its port is the same program without the schedule,
        # and the marker tells systems/oatlog/build to generate a saturation loop around step().
        (out / "oatlog").mkdir(exist_ok=True)
        (out / "oatlog" / f"horner-{n}.egg").write_text(";; oatlog-port: saturate\n" + program)
        print(f"horner-{n}.egg")


if __name__ == "__main__":
    main()
